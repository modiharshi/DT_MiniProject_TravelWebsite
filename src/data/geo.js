// Stylised, hand-placed geography. Not survey-accurate: this is an illustration.
// Everything lives in one 1000-unit coordinate system so the camera never drifts.

const LON0 = 67, LAT0 = 37.5, KX = 31, KY = 29, OX = 30, OY = 50;

export const project = ([lon, lat]) => [(lon - LON0) * KX + OX, (LAT0 - lat) * KY + OY];

// Catmull-Rom -> cubic Bezier. `k` is how rounded the hand-drawn corners get.
export function smoothPath(lonlat, { closed = true, k = 0.11 } = {}) {
  const p = lonlat.map(project);
  const n = p.length;
  const at = (i) => (closed ? p[(i + n) % n] : p[Math.max(0, Math.min(n - 1, i))]);
  const f = (v) => Math.round(v * 10) / 10;
  let d = `M${f(p[0][0])} ${f(p[0][1])}`;
  const last = closed ? n : n - 1;
  for (let i = 0; i < last; i++) {
    const p0 = at(i - 1), p1 = at(i), p2 = at(i + 1), p3 = at(i + 2);
    const c1 = [p1[0] + (p2[0] - p0[0]) * k, p1[1] + (p2[1] - p0[1]) * k];
    const c2 = [p2[0] - (p3[0] - p1[0]) * k, p2[1] - (p3[1] - p1[1]) * k];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return closed ? d + 'Z' : d;
}

export function bounds(lonlat) {
  const p = lonlat.map(project);
  const xs = p.map((q) => q[0]), ys = p.map((q) => q[1]);
  const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
  return { cx: (x0 + x1) / 2, cy: (y0 + y1) / 2, w: x1 - x0, h: y1 - y0 };
}

